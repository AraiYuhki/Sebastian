#!/bin/sh
# =============================================================================
# poll-and-run.sh — リモートの新しいコミットを取り込んで sebastian-ci を実行する
# =============================================================================
# cron や systemd timer から定期的に呼び出すことで、「push されたら CI が走る」を
# サーバー常駐なしで実現します（ポーリング方式）。
#
# 使い方:
#   poll-and-run.sh /path/to/repo [sebastian-ci への追加引数...]
#
# ポイント:
#   - 新しいコミットが無ければ sebastian-ci が「実行済みのためスキップ」と判断する
#     ため、空振りのコストはほぼゼロです（コンテナは起動しません）。
#   - 無人実行のため --yes を付けています（approval の承認ゲートを自動承認）。
#     承認を人間に残したいパイプラインでは --yes を外してください（承認待ちの
#     ジョブは失敗になります）。
#   - 多重起動の防止は呼び出し側で行ってください（crontab.example の flock 参照）。
# =============================================================================
set -eu

REPO="${1:?リポジトリパスを指定してください}"
shift

cd "$REPO"

# リモートの最新を取得し、早送りできる場合だけ取り込む（ローカルの作業は壊さない）
git fetch --quiet origin
if ! git merge --ff-only --quiet '@{upstream}' 2>/dev/null; then
    echo "⚠ 早送りマージできません（ローカルにコミットがあるか、上流が未設定です）。現在のコミットのまま実行します。" >&2
fi

# 実行（同じコミットなら自動でスキップされる）
exec sebastian-ci . --yes "$@"
